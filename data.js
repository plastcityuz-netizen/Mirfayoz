const sum = (values) => values.reduce((a, b) => a + b, 0);
export const dataService = {
  async getSnapshot(period = 2) {
    const range =
      period === 4
        ? Array.from({ length: 12 }, (_, i) => i)
        : period === 3
          ? [8, 9, 10]
          : [10];
    const factor = [0.05, 0.25, 1, 1, 1][period];
    const revenue = sum(range.map((i) => DEMO_DATA.revenue[i])) * factor * 1e6;
    const cost = sum(range.map((i) => DEMO_DATA.cost[i])) * factor * 1e6;
    return {
      revenue,
      cost,
      profit: revenue - cost,
      balance: 84000000 + revenue - cost,
      debt: sum(DEMO_DATA.debt.map((x) => x.value)),
      payable: 17200000,
      stock: sum(DEMO_DATA.inventory.map((x) => x.value)),
    };
  },
  async getRows(page, role, period) {
    if (!RBAC[role].includes(page)) return [];
    if (page === "ombor")
      return DEMO_DATA.inventory
        .filter((x) => role !== 4 || x.raw)
        .map((x) => ({
          ...x,
          value: role === 2 ? x.qty : x.value,
          kind: x.raw ? "materialItem" : "item",
        }));
    if (page === "savdo" || page === "hisob" || page === "moliya") {
      const months =
        period === 4
          ? Array.from({ length: 12 }, (_, i) => i)
          : period === 3
            ? [8, 9, 10]
            : [10];
      return DEMO_DATA.transactions
        .filter(
          (x) => months.includes(x.month) && (page !== "savdo" || !x.type),
        )
        .map((x) => ({
          ...x,
          day: period === 0 ? 20 : x.day,
          value:
            (x.type ? DEMO_DATA.cost : DEMO_DATA.revenue)[x.month] *
            1e6 *
            [0.05, 0.25, 1, 1, 1][period],
          kind: page === "savdo" ? "customer" : "operation",
        }));
    }
    return Array.from({ length: 8 }, (_, i) => ({
      id: i + 1,
      value: (i + 2) * [0.05, 0.25, 1, 3, 12][period] * 350000,
      kind:
        page === "hr"
          ? "employee"
          : page === "ishlab"
            ? "item"
            : "materialItem",
    }));
  },
  async answer(index) {
    await new Promise((resolve) => setTimeout(resolve, 420));
    return index;
  },
};
